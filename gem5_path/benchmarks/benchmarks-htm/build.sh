#!/bin/bash

set -xv
SCRIPT_DIR="$(readlink -fm "$(dirname $0)")"
SCRIPT_COMMAND="$(basename "$0")"
BENCHMARKS_ROOT="${SCRIPT_DIR}"
STAMP_SYMLINK_NAME="stamp"
GEM5_SYMLINK_NAME="gem5"
STAMP_DIR="${BENCHMARKS_ROOT}/${STAMP_SYMLINK_NAME}"
export ARCH="${ARCH:-x86}"


# Create links gem5->stamp and stamp->gem5
cd "${BENCHMARKS_ROOT}"
PASSED=0
if [[ -L ${STAMP_SYMLINK_NAME} ]] ; then
    STAMP_DIR=$(readlink -f ${STAMP_SYMLINK_NAME})
    if [[ -d ${STAMP_DIR} ]] ; then
        cd ${STAMP_DIR}
        if [[ -L ${GEM5_SYMLINK_NAME} ]] ; then
            GEM5_DIR=$(readlink -f ${GEM5_SYMLINK_NAME})
            if [[ -d ${GEM5_DIR} ]] ; then
                cd ${GEM5_DIR}
                if [[ "$(readlink -nf ${SCRIPT_DIR}/../../..)" == "$(readlink -nf ${PWD})" ]] ; then
                    PASSED=1
                else
                    EXPECTED_PATH="$(readlink -nf ${SCRIPT_DIR}/../../..)"
                    echo "Error: unexpected path for gem5 symlink (expected $EXPECTED_PATH)"
                fi
            else
                echo "Error: found gem5 symlink in ${STAMP_DIR} but it does not point to a valid directory"
            fi
        else
            echo "Error: cannot find symlink to gem5 directory in ${STAMP_DIR}"
        fi
    else
        echo "Error: found stamp symlink in ${BENCHMARKS_ROOT} but it does not point to a valid directory"
    fi
else
    echo "Error: cannot find symlink to stamp directory in ${BENCHMARKS_ROOT}"
fi

if [[ $PASSED -eq 0 ]]
then
    echo "Required symlinks can be generated by tasks-gem5 (actions: init-caps, init-public)"
    exit
fi

while [[ $# -gt 0 ]]
do
    key="$1"
    case $key in
	-c|--clean)
            # Do not build, only clean
	    ONLY_CLEAN="clean"
	    shift # past argument
	    ;;
	-nc|--noclean)
            # Do not clean before making each benchmark
	    DONT_CLEAN="yes"
	    shift # past argument
	    ;;
        -gcc48)
            # Do not clean before making each benchmark
            if [[ "$USER" == "root" ]] ; then
                echo "Updating alternatives for gcc to gcc-4.8"
                update-alternatives --set gcc /usr/bin/gcc-4.8
            else
                echo "Cannot update alternatives: This script must be run as 'root' (user is $USER)."
                echo "This option is meant to be used after chroot'ing into a disk image."
                exit
            fi
            shift # past argument
            ;;
	--default)
	    ;;
	*)
            # unknown option
	    ;;
    esac
    shift # past argument or value
done


BENCHMARKS="\
  bayes \
  genome \
  intruder \
  kmeans \
  labyrinth \
  ssca2 \
  vacation \
  yada \
"
#BENCHMARKS="intruder"

DEFAULT_FLAVOURS="htm.empty htm.fallbacklock htm.fallbacklock2phase htm.sgl"

if [[ -z $FLAVOURS ]]; then 
    FLAVOURS=${DEFAULT_FLAVOURS}
fi

if [[ -z $DONT_CLEAN ]]; then 
    echo "Cleaning..."
    for SUFFIX in $FLAVOURS ; do
        for b in $BENCHMARKS ; do
            cd "${STAMP_DIR}/$b"
    	    make -f Makefile.${SUFFIX} clean
        done
    done
fi

# Cleanup libraries
cd "${BENCHMARKS_ROOT}/libs"
make ARCH=${ARCH} clean

if [[ -n $ONLY_CLEAN ]]; then exit; fi

for SUFFIX in $FLAVOURS ; do

    for b in $BENCHMARKS ; do
        cd "${STAMP_DIR}/$b"
        # IMPORTANT: Clean up library objects compiled with specific CFLAGS
    	make -C ../lib clean
        # IMPORTANT: Clean up benchmark objects compiled with specific
        # CFLAGS (-DLOG_INTERVALS)
    	make -f Makefile.${SUFFIX} clean
    	make -f Makefile.${SUFFIX}
    done
done
